function Diamond({ payload, cls }) {
  const cx = W / 2;
  const cy = H / 2;
  const R = Math.min(W, H) / 2 - 4;
  const S = 2 * R;
  const innerR = R - 0.05 * S * Math.SQRT2;
  const [upper, lower] = halves(cls);

  const poly = (r) => `${cx},${cy - r} ${cx + r},${cy} ${cx},${cy + r} ${cx - r},${cy}`;

  const bandW = S / 14;
  const stripes = [];
  for (let k = 0; k < 14; k += 2) stripes.push(cx - R + k * bandW);

  const numeral =
    cls.numeral === "1"
      ? `${payload.division || ""}${payload.compatGroup || ""}`.trim() || cls.numeral
      : cls.numeral;
  const middle = cls.name;
  const subs = String(payload.subsidiaryRisks || "").trim();

  const upperInk = inkOn(upper);
  const lowerInk = inkOn(lower);

  return (
    <g>
      <defs>
        <clipPath id="haz-dia"><polygon points={poly(R)} /></clipPath>
        <clipPath id="haz-upper"><rect x="0" y={cy - R - 4} width={W} height={R + 4} /></clipPath>
      </defs>

      <rect width={W} height={H} fill={WHITE} />
      <g clipPath="url(#haz-dia)">
        {cls.pattern === "stripesRed7" &&
          stripes.map((x) => <rect key={x} x={x} y={cy - R} width={bandW} height={S} fill={RED} />)}
        {cls.pattern === "stripesBlack7Upper" && (
          <g clipPath="url(#haz-upper)">
            {stripes.map((x) => <rect key={x} x={x} y={cy - R} width={bandW} height={S} fill={BLACK} />)}
          </g>
        )}
        {cls.pattern.startsWith("half") && (
          <>
            <rect x={cx - R} y={cy - R} width={S} height={R} fill={upper} />
            <rect x={cx - R} y={cy} width={S} height={R} fill={lower} />
          </>
        )}
        {cls.pattern === "solid" && <rect x={cx - R} y={cy - R} width={S} height={S} fill={cls.hex} />}
      </g>

      <polygon points={poly(R)} fill="none" stroke={BLACK} strokeWidth="4" />
      <polygon points={poly(innerR)} fill="none" stroke={BLACK} strokeWidth="3" />

      {cls.symbol !== "none" && (
        <g transform={`translate(${cx - 0.15 * S} ${cy - 0.5 * S}) scale(${(0.3 * S) / 100})`}>
          {symbolArt(cls.symbol, upperInk)}
        </g>
      )}

      <text
        x={cx}
        y={cy + 0.055 * S + 8}
        fontSize={Math.min(26, (0.05 * S) / 0.72)}
        fontWeight="700"
        fill={lowerInk}
        textAnchor="middle"
        fontFamily="Inter, Helvetica, Arial, sans-serif"
      >
        {middle.length > 42 ? middle.slice(0, 39) + "..." : middle}
      </text>

      <text
        x={cx}
        y={cy + 0.215 * S + 20}
        fontSize={(0.127 * S) / 0.72}
        fontWeight="700"
        fill={lowerInk}
        textAnchor="middle"
        fontFamily="Inter, Helvetica, Arial, sans-serif"
      >
        {numeral}
      </text>
      {numeral.startsWith("9") && (
        <rect x={cx - 22} y={cy + 0.215 * S + 26} width={44} height={3} fill={lowerInk} />
      )}
      {subs && (
        <text
          x={cx}
          y={cy + 0.215 * S + 46}
          fontSize="14"
          fill={lowerInk}
          textAnchor="middle"
          fontFamily="Inter, Helvetica, Arial, sans-serif"
        >
          SUB: {subs}
        </text>
      )}

      {cls.symbol === "trefoil" && payload.radiationCategory && (
        <g>
          {["I", "II", "III"].map((cat, i) => (
            <g key={cat} transform={`translate(${cx + 62} ${cy - 96 + i * 34})`}>
              <rect width="32" height="30" fill={WHITE} stroke={BLACK} strokeWidth="2.5" />
              <text x="16" y="21" fontSize="15" fontWeight="700" fill={BLACK} textAnchor="middle" fontFamily="Inter, Helvetica, Arial, sans-serif">
                {cat}
              </text>
            </g>
          ))}
        </g>
      )}

      <Footer />
    </g>
  );
}

