function resolveClass(key) {
  const k = String(key || "").trim().toUpperCase();
  if (CLASSES[k]) return CLASSES[k];
  switch (k.charAt(0)) {
    case "1": return CLASSES["1"];
    case "2":
      if (k.startsWith("2.2") || k === "22") return CLASSES["2.2"];
      if (k.startsWith("2.3") || k === "23") return CLASSES["2.3"];
      return CLASSES["2.1"];
    case "3": return CLASSES["3"];
    case "4":
      if (k.startsWith("4.2")) return CLASSES["4.2"];
      if (k.startsWith("4.3")) return CLASSES["4.3"];
      return CLASSES["4.1"];
    case "5": return k.startsWith("5.2") ? CLASSES["5.2"] : CLASSES["5.1"];
    case "6": return k.startsWith("6.2") ? CLASSES["6.2"] : CLASSES["6.1"];
    case "7": return CLASSES["7"];
    case "8": return CLASSES["8"];
    default: return CLASSES["9"];
  }
}

function luminance(hex) {
  const h = hex.replace("#", "");
  const r = parseInt(h.slice(0, 2), 16) / 255;
  const g = parseInt(h.slice(2, 4), 16) / 255;
  const b = parseInt(h.slice(4, 6), 16) / 255;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
const inkOn = (bg) => (luminance(bg) > 0.55 ? BLACK : WHITE);

function halves(hc) {
  switch (hc.pattern) {
    case "halfRedBottom": return [WHITE, RED];
    case "halfTopRedYellow": return [RED, YELLOW];
    case "halfYellowWhite": return [RYEL, WHITE];
    case "halfBlackBottom": return [WHITE, BLACK];
    default: return [hc.hex, hc.hex];
  }
}

